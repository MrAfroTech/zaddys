/**
 * Regenerates the Zaddys menu_items seed in db/schema.sql from src/data/menu.js.
 * One orderable row per size; add-ons become their own rows, named so staff and
 * customers can tell what they attach to.
 *
 *   node scripts/menu-seed.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { menuSections } from '../src/data/menu.js';

const START = '-- BEGIN zaddys menu seed (generated by scripts/menu-seed.mjs — do not edit by hand)';
const END = '-- END zaddys menu seed';

const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const sizeSlug = (size) => size.replace(/"/g, 'in').toLowerCase();

const rows = [];
for (const section of menuSections) {
  for (const item of section.items) {
    const sized = section.sizes?.length > 1;
    item.prices.forEach((cents, i) => {
      const size = sized ? section.sizes[i] : null;
      let name = size ? `${item.name} ${size}` : item.name;
      if (item.addOn) name = `${name} (${section.title} add-on)`;
      const notes = [item.availability, section.availability, item.description].filter(Boolean);
      rows.push({
        slug: size ? `${item.slug}-${sizeSlug(size)}` : item.slug,
        name,
        description: notes.length ? notes.join(' — ') : null,
        cents,
        category: section.title,
        order: (rows.length + 1) * 10,
      });
    });
  }
}

const sql = `${START}
insert into public.menu_items (client_id, menu_id, slug, name, description, price_cents, category, display_order, is_demo)
select c.id, m.id, v.slug, v.name, v.description, v.price_cents, v.category, v.display_order, false
  from public.clients c
  join public.menus m on m.client_id = c.id and m.name = 'Menu'
 cross join (values
${rows.map((r) => `   (${q(r.slug)}, ${q(r.name)}, ${q(r.description)}, ${r.cents}, ${q(r.category)}, ${r.order})`).join(',\n')}
 ) as v (slug, name, description, price_cents, category, display_order)
 where c.slug = 'zaddys'
on conflict (client_id, slug) do nothing;
-- Earlier drafts seeded placeholder items; keep them off the live menu.
update public.menu_items mi set is_available = false
  from public.clients c
 where mi.client_id = c.id and c.slug = 'zaddys' and mi.is_demo;
${END}`;

const path = new URL('../db/schema.sql', import.meta.url);
let schema = readFileSync(path, 'utf8');
const a = schema.indexOf(START);
const b = schema.indexOf(END);
if (a === -1 || b === -1) throw new Error('seed markers not found in db/schema.sql');
schema = schema.slice(0, a) + sql + schema.slice(b + END.length);
writeFileSync(path, schema);
console.log(`wrote ${rows.length} menu_items rows`);
